def main():
    p = argparse.ArgumentParser()
    p.add_argument("底稿", type=Path, nargs="?")
    p.add_argument("--自检", action="store_true")
    a = p.parse_args()
    if a.自检:
        d = 自测样本()
        好 = 审查(d)
        if 好:
            print("全周期营销自检：合格样本被误拒")
            for x in 好: print("- " + x)
            return 1
        坏 = json.loads(json.dumps(d, ensure_ascii=False))
        坏["全周期营销"] = [x for x in 坏["全周期营销"] if x["阶段责任"] != "sustain"]
        if not any("sustain" in x for x in 审查(坏)):
            print("全周期营销自检：缺持续营销责任样本未被拒绝")
            return 1
        浅 = json.loads(json.dumps(d, ensure_ascii=False))
        浅["全周期营销"][0]["重点动作执行方案"] = [{"方案名称": "周末生活节"}]
        if not any("重点动作执行方案" in x for x in 审查(浅)):
            print("全周期营销自检：只有活动名的浅颗粒样本未被拒绝")
            return 1
        print("全周期营销自检：合格样本通过；缺阶段责任与只有活动名的浅颗粒样本均被拒绝。")
        return 0
    elif a.底稿:
        try:
            d = json.loads(a.底稿.read_text(encoding="utf-8"))
        except Exception as e:
            print("全周期营销审查：无法读取：", e)
            return 2
    else:
        p.error("必须提供底稿或使用--自检")
    失败 = 审查(d)
