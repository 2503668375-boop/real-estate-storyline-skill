def 文本(v):
    return re.sub(r"\s+", "", str(v or "")).strip()


def 有效(v, n=4):
    return len(文本(v)) >= n and 文本(v) not in {"待定", "待核实", "TBD", "-", "—"} | 通用占位


def 有数字(v):
    return bool(re.search(r"\d", 文本(v)))


def 审查列表记录(记录, 字段, 前缀, 失败, 最少):
    if not isinstance(记录, list) or len(记录) < 最少:
        失败.append(f"{前缀}少于{最少}条")
        return
    for i, x in enumerate(记录, 1):
        if not isinstance(x, dict):
            失败.append(f"{前缀}{i}不是结构化记录")
            continue
        for k in 字段:
            if not 有效(x.get(k), 1):
                失败.append(f"{前缀}{i}缺少{k}")


def 审查(d):
    失败 = []
    for k, n in (("营销总主题", 8), ("对应主线命题", 20), ("总经营目标", 10)):
        if not 有效(d.get(k), n):
            失败.append("缺少有效字段：" + k)
    表 = d.get("全周期营销")
    if not isinstance(表, list) or len(表) < 12:
        失败.append(f"全周期营销少于12阶段（实际{len(表) if isinstance(表, list) else 0}）")
        表 = 表 if isinstance(表, list) else []
    覆盖, 类型, 闭环阶段 = set(), set(), 0
    for i, x in enumerate(表, 1):
        if not isinstance(x, dict):
            失败.append(f"阶段{i}不是结构化记录")
            continue
        名 = 文本(x.get("阶段"))
        if not 有效(名, 3):
            失败.append(f"阶段{i}缺少有效中文名称")
        责任 = 文本(x.get("阶段责任"))
        if 责任 not in 阶段责任:
            失败.append(f"阶段「{名 or i}」责任代码无效：{责任 or '空'}")
        else:
            覆盖.add(责任)
        for k, n in (
            ("经营问题", 8), ("目标库存", 4), ("主受众", 4),
            ("客户信念任务", 8), ("阶段主题", 4), ("主证据", 6),
            ("核心动作", 6), ("线上任务", 6), ("线下验证", 6),
            ("圈层与关系路径", 6), ("私域与销售承接", 6),
            ("负责人", 2), ("预算", 2), ("KPI", 4),
            ("切换信号", 6), ("风险与合规", 6), ("阶段复盘产出", 6),
        ):
            if not 有效(x.get(k), n):
                失败.append(f"阶段「{名 or i}」缺少{k}")
        动作 = x.get("关键动作")
        if not isinstance(动作, list) or len(动作) < 3:
            失败.append(f"阶段「{名 or i}」关键动作少于3个")
            动作 = 动作 if isinstance(动作, list) else []
        for j, a in enumerate(动作, 1):
            if not isinstance(a, dict):
                失败.append(f"阶段「{名 or i}」动作{j}不是结构化记录")
                continue
            类型.add(文本(a.get("动作类型")))
            for k in 动作字段:
                n = 6 if k in {"要解决的客户顾虑", "项目证据", "具体做法", "动作目的", "客户下一步", "项目获得什么", "切换信号", "风险与合规", "复盘产出"} else 2
                if not 有效(a.get(k), n):
                    失败.append(f"阶段「{名 or i}」动作{j}缺少{k}")
        方案 = x.get("重点动作执行方案")
        最少方案 = 2 if 责任 in 重点责任 else 1
        if not isinstance(方案, list) or len(方案) < 最少方案:
            失败.append(f"阶段「{名 or i}」重点动作执行方案少于{最少方案}个")
            方案 = 方案 if isinstance(方案, list) else []
        for j, 包 in enumerate(方案, 1):
            前缀 = f"阶段「{名 or i}」重点动作执行方案{j}"
            if not isinstance(包, dict):
                失败.append(前缀 + "不是结构化记录")
                continue
            for k in 方案字段:
                if not 有效(包.get(k), 3):
                    失败.append(前缀 + "缺少" + k)
            审查列表记录(包.get("预热内容表"), 内容字段, 前缀 + "预热内容", 失败, 3)
            审查列表记录(包.get("现场流程表"), 步骤字段, 前缀 + "现场步骤", 失败, 6)
            审查列表记录(包.get("物料清单"), ["名称", "规格", "数量", "到位时间", "责任人", "替代方案"], 前缀 + "物料", 失败, 3)
            if not isinstance(包.get("人员RACI"), list) or len(包.get("人员RACI")) < 4:
                失败.append(前缀 + "人员RACI少于4个岗位")
            if not isinstance(包.get("预算拆分"), list) or len(包.get("预算拆分")) < 4:
                失败.append(前缀 + "预算拆分少于4项")
            elif not all(有数字(z.get("金额或公式")) for z in 包["预算拆分"] if isinstance(z, dict)):
                失败.append(前缀 + "预算拆分缺金额或可计算公式")
            if not isinstance(包.get("KPI表"), list) or len(包.get("KPI表")) < 3:
                失败.append(前缀 + "KPI表少于3项")
            else:
                for z in 包["KPI表"]:
                    if not isinstance(z, dict) or not all(有效(z.get(k), 1) for k in ("指标", "基线", "目标值", "统计周期", "数据源", "责任人")):
                        失败.append(前缀 + "KPI缺指标/基线/目标值/周期/数据源/责任人")
                        break
                if not any(有数字(z.get("目标值")) for z in 包["KPI表"] if isinstance(z, dict)):
                    失败.append(前缀 + "KPI目标没有数值或比例")
        阶段文本 = 文本(x)
        if all(any(w in 阶段文本 for w in group) for group in (
            ("线上", "搜索", "直播", "内容"),
            ("线下", "案场", "样板", "工地", "实景"),
            ("圈层", "关系载体", "私域", "销售承接"),
        )):
            闭环阶段 += 1
    for 责任 in 阶段责任:
        if 责任 not in 覆盖:
            失败.append("缺少标准阶段责任：" + 责任)
    if len(类型 - {""}) < 5:
        失败.append(f"营销动作类型少于5类（实际{len(类型 - {''})}类）")
    if 闭环阶段 < 8:
        失败.append(f"形成线上触达—线下验证—关系/销售承接闭环的阶段少于8个（实际{闭环阶段}个）")

