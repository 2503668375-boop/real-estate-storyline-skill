    必要漏斗 = ["有效触达", "留资", "有效线索", "预约", "到访", "复访", "登记/冻资", "认筹", "选房", "签约", "回款", "转介绍"]
    if not isinstance(漏斗, list):
        失败.append("缺少完整漏斗")
        漏斗 = []
    全漏斗 = "".join(文本(x) for x in 漏斗)
    for k in 必要漏斗:
        if 文本(k) not in 全漏斗:
            失败.append("漏斗缺少：" + k)
    return list(dict.fromkeys(失败))


